"""Write the "Top performing models" page for the public website.

  python benchmarks/scripts/site_top_models.py [--out benchmarks/results/top-models.md] [--top 10]

Reads the same results as readme_status.py (the newest dated report each agent appears in) and ranks
the benchmark agents that passed at least one task: by pass rate, then mean quality, then fewer
seconds per task. The heading carries an asterisk, and its footnote says what the numbers do and do
not show. The page is plain Markdown with no front matter, so a site can fetch it as it is from
https://raw.githubusercontent.com/CLR-Technologies-Inc/foames/main/benchmarks/results/top-models.md
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from readme_status import BENCH, latest_results, provider, use

HOW_RUN = {
	"claude-code": "Claude Code, Claude subscription",
	"gemini": "aider, Gemini API free tier",
	"openrouter": "aider, OpenRouter free model",
	"nvidia_nim": "aider, NVIDIA Build free credits",
	"groq": "aider, Groq free tier",
	"mistral": "aider, Mistral free tier",
	"cerebras": "aider, Cerebras free tier",
	"ollama-runner": "aider, Ollama on a 4-vCPU CPU runner",
	"ollama-gpu": "aider, Ollama on a notebook GPU",
}
REPO = "https://github.com/CLR-Technologies-Inc/foames/blob/main/benchmarks"


def ranked(agents: list, results: dict, top: int) -> list:
	rows = []
	for a in agents:
		if a["name"] not in results:
			continue
		day, s, ecl = results[a["name"]]
		if s.get("success_rate", 0) <= 0:
			continue
		rows.append((a, day, s, ecl))
	rows.sort(key=lambda r: (-r[2]["success_rate"], -r[2].get("quality", 0), r[2].get("mean_seconds", 0)))
	return rows[:top]


def page(rows: list) -> str:
	days = sorted({day for _, day, _, _ in rows})
	lines = [
		"<!-- Generated by benchmarks/scripts/site_top_models.py from the FoaMES agent benchmark. Do not edit by hand. -->",
		"",
		"## Top performing models*",
		"",
		"How well each model did as a coding agent on FoaMES manufacturing tasks: repairing production counting, "
		+ "building OEE and SPC, honouring ERP throttling, mining a process, specifying recovery after a network "
		+ "outage, and checking energy-saving claims from 29 industrial sector case studies.",
		"",
		"| Rank | Model | How it ran | Built for | Tasks run | Pass rate (95% range) | ECL reached | Cost |",
		"| ---: | --- | --- | --- | ---: | --- | --- | ---: |",
	]
	for i, (a, _day, s, ecl) in enumerate(rows, 1):
		lo, hi = s.get("success_ci95") or (None, None)
		rng = f" ({round(100 * lo)}% to {round(100 * hi)}%)" if lo is not None else ""
		lines.append(
			f"| {i} | `{s.get('model') or a.get('model', '')}` | {HOW_RUN.get(provider(a), provider(a))} | {use(a)} | "
			f"{s['runs']} | {round(100 * s['success_rate'])}%{rng} | {('ECL ' + str(ecl)) if ecl else 'none'} | "
			f"${s.get('total_cost_usd', 0):.2f} |"
		)
	report = ", ".join(f"[{d}]({REPO}/results/{d}/README.md)" for d in days) or "none yet"
	lines += [
		"",
		"\\* From the FoaMES agent benchmark, report " + report + ". Read these numbers with care:",
		"",
		"- Each model ran each task once, so one pass or fail moves a small model's rate a lot; the 95% range shows how much.",
		"- Not every model ran the same tasks. Most ran the six core tasks; the Claude models and some hosted models also ran the 29 sector case studies, and some hosted runs were cut short by time limits.",
		"- The Claude models ran through Claude Code on a Claude subscription, not the API, so they show $0. Other models ran with aider in GitHub Actions on free tiers, or on 4-vCPU runners without a GPU, where most local models ran out of time before they could finish.",
		"- ECL is the Equipment Complexity Level at which the model passed every task at that level and below. One failed task at a low level gives none. Fable 5.2 and Sonnet 5.5 show none because one task's wording could be read two ways; it has since been fixed and their runs are kept as graded.",
		"- A pass means every invariant test passed: counters never invent production, nothing posts to the ERP twice, and so on. The scores describe this benchmark only, not the models in general.",
		"- Only models that passed at least one task are listed. The full results, including every model that passed none, are in the dated report and in the [benchmark README]("
		+ REPO
		+ "/README.md).",
		"",
	]
	return "\n".join(lines)


def main(argv=None):
	ap = argparse.ArgumentParser()
	ap.add_argument("--out", type=Path, default=BENCH / "results" / "top-models.md")
	ap.add_argument("--top", type=int, default=10)
	opts = ap.parse_args(argv)
	agents = [
		a
		for a in json.loads((BENCH / "agents.json").read_text(encoding="utf-8"))["agents"]
		if (a["name"].startswith("aider-") and a["name"] != "aider-local")
		or (a.get("harness") == "claude-code" and a.get("_runs_on") == "subscription")
	]
	opts.out.write_text(page(ranked(agents, latest_results(BENCH / "results"), opts.top)), encoding="utf-8")
	print(f"wrote {opts.out}")


if __name__ == "__main__":
	main()
